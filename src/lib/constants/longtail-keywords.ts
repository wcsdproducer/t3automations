export function getLongTailQueueForNiche(service: string): LongTailTopic[] {
  const s = (service || '').toLowerCase();
  if (s.includes('appliance')) return LONGTAIL_KEYWORD_QUEUES.appliance;
  if (s.includes('epoxy') || s.includes('floor')) return LONGTAIL_KEYWORD_QUEUES.epoxy;
  if (s.includes('concrete') || s.includes('paving')) return LONGTAIL_KEYWORD_QUEUES.concrete;
  if (s.includes('tree')) return LONGTAIL_KEYWORD_QUEUES.tree;
  if (s.includes('pest')) return LONGTAIL_KEYWORD_QUEUES.pest;
  if (s.includes('junk') || s.includes('removal')) return LONGTAIL_KEYWORD_QUEUES.junk;
  return [];
}
